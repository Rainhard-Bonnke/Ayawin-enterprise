#!/usr/bin/env node
/**
 * Generate production secrets and write backend/.env.production
 * Usage:
 *   node scripts/go-live-init.cjs
 *   node scripts/go-live-init.cjs --apply   (copies to .env after backup)
 */
const fs = require('fs');
const path = require('path');
const { randomSecret, randomHex } = require('./lib/secrets.cjs');

const root = path.resolve(__dirname, '..');
const examplePath = path.join(root, '.env.example');
const outPath = path.join(root, '.env.production');
const envPath = path.join(root, '.env');
const apply = process.argv.includes('--apply');

const frontendUrl = process.env.GO_LIVE_FRONTEND_URL || 'https://erp.yourdomain.co.ke';
const apiUrl = process.env.GO_LIVE_API_URL || 'https://api.yourdomain.co.ke';

const secrets = {
  JWT_SECRET: randomSecret(48),
  PII_ENCRYPTION_KEY: randomHex(32),
  MFA_ENCRYPTION_KEY: randomHex(32),
  INTERNAL_API_KEY: randomSecret(24),
  MPESA_CALLBACK_SECRET: randomSecret(24),
};

let template = fs.readFileSync(examplePath, 'utf8');

template = template
  .replace(/^ENABLE_DEMO_MODE=.*/m, 'ENABLE_DEMO_MODE=false')
  .replace(/^NODE_ENV=.*/m, 'NODE_ENV=production')
  .replace(/^STRICT_PRODUCTION_CONFIG=.*/m, 'STRICT_PRODUCTION_CONFIG=true')
  .replace(/^ENABLE_LEGACY_API=.*/m, 'ENABLE_LEGACY_API=false')
  .replace(/^JWT_SECRET=.*/m, `JWT_SECRET=${secrets.JWT_SECRET}`)
  .replace(/^PII_ENCRYPTION_KEY=.*/m, `PII_ENCRYPTION_KEY=${secrets.PII_ENCRYPTION_KEY}`)
  .replace(/^MFA_ENCRYPTION_KEY=.*/m, `MFA_ENCRYPTION_KEY=${secrets.MFA_ENCRYPTION_KEY}`)
  .replace(/^INTERNAL_API_KEY=.*/m, `INTERNAL_API_KEY=${secrets.INTERNAL_API_KEY}`)
  .replace(/^MPESA_CALLBACK_SECRET=.*/m, `MPESA_CALLBACK_SECRET=${secrets.MPESA_CALLBACK_SECRET}`)
  .replace(/^CORS_ORIGINS=.*/m, `CORS_ORIGINS=${frontendUrl}`)
  .replace(/^APP_BASE_URL=.*/m, `APP_BASE_URL=${frontendUrl}`)
  .replace(/^ADMIN_PASSWORD=.*/m, 'ADMIN_PASSWORD=');

if (!template.includes('GO_LIVE_INITIALIZED')) {
  template += '\n# GO_LIVE_INITIALIZED=true — generated by go-live-init.cjs\n';
}

fs.writeFileSync(outPath, template, 'utf8');
console.log(`\nWrote ${outPath}`);
console.log('\nGenerated secrets (also saved in file — store in your password manager):');
console.log(`  JWT_SECRET=${secrets.JWT_SECRET.slice(0, 12)}…`);
console.log(`  PII_ENCRYPTION_KEY=${secrets.PII_ENCRYPTION_KEY.slice(0, 12)}…`);

if (apply) {
  if (fs.existsSync(envPath)) {
    const backup = `${envPath}.backup-${Date.now()}`;
    fs.copyFileSync(envPath, backup);
    console.log(`\nBacked up existing .env → ${backup}`);
  }
  fs.copyFileSync(outPath, envPath);
  console.log(`Applied → ${envPath}`);
  console.log('\nNext: set NEW_ADMIN_PASSWORD and run: npm run go-live:password');
} else {
  console.log('\nReview the file, then either:');
  console.log('  copy .env.production → .env   (or run with --apply)');
  console.log('  deploy .env.production as your host environment variables');
}
